def style_header(ws, cols):
    for i, (name, required, _, width) in enumerate(cols, start=1):
        c = ws.cell(row=1, column=i, value=name + (" *" if required else ""))
        c.font = Font(bold=True, color="FFFFFF" if not required else "000000", size=11)
        c.fill = PatternFill("solid", fgColor=ORANGE if required else NAVY)
        c.alignment = CENTER
        c.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.row_dimensions[1].height = 48
    ws.freeze_panes = "B2"
    ws.sheet_view.rightToLeft = True


def add_validations(ws, cols):
    for i, (name, required, rule, _) in enumerate(cols, start=1):
        col = get_column_letter(i)
        rng = f"{col}2:{col}{ROWS + 1}"
        dv = None
        if rule is None:
            pass
        elif rule == "date":
            dv = DataValidation(type="date", operator="between",
                                formula1="DATE(1930,1,1)", formula2="DATE(2100,12,31)",
                                allow_blank=True)
            dv.error = "اكتب تاريخًا صحيحًا بصيغة سنة-شهر-يوم"
            for r in range(2, ROWS + 2):
                ws.cell(row=r, column=i).number_format = "yyyy-mm-dd"
        elif rule[0] == "list":
            lst = rule[1]
            lc = LIST_COL[lst]
            dv = DataValidation(type="list",
                                formula1=f"='القوائم'!${lc}$2:${lc}${len(LISTS[lst]) + 1}",
                                allow_blank=True)
            dv.error = "اختر من القائمة"
        elif rule[0] == "len":
            dv = DataValidation(type="textLength", operator="equal",
                                formula1=str(rule[1]), allow_blank=True)
            dv.error = f"يجب أن يتكون من {rule[1]} خانة بالضبط"
            for r in range(2, ROWS + 2):
                ws.cell(row=r, column=i).number_format = "@"
        elif rule[0] == "text":
            for r in range(2, ROWS + 2):
                ws.cell(row=r, column=i).number_format = "@"
        if dv is not None:
            dv.showErrorMessage = True
            dv.errorTitle = "قيمة غير صحيحة"
            ws.add_data_validation(dv)
            dv.add(rng)


